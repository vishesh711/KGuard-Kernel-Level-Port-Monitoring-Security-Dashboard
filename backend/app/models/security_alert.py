"""
Security Alert Database Model

This module defines the SecurityAlert model for storing security alerts
generated by the anomaly detection system.
"""

from sqlalchemy import Column, Integer, String, DateTime, Boolean, Text, JSON, Enum
from sqlalchemy.sql import func
from datetime import datetime
import enum

from ..database import Base


class AlertSeverity(enum.Enum):
    """Alert severity levels"""
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class AlertType(enum.Enum):
    """Types of security alerts"""
    PORT_SCAN = "PORT_SCAN"
    BRUTE_FORCE = "BRUTE_FORCE"
    SUSPICIOUS_PORT = "SUSPICIOUS_PORT"
    HIGH_FREQUENCY = "HIGH_FREQUENCY"
    UNUSUAL_TRAFFIC = "UNUSUAL_TRAFFIC"
    UNKNOWN_PROTOCOL = "UNKNOWN_PROTOCOL"


class SecurityAlert(Base):
    """
    Security Alert Model
    
    Stores security alerts generated by the anomaly detection system
    when suspicious network activity is detected.
    """
    
    __tablename__ = "security_alerts"
    
    # Primary key
    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    
    # Timestamp information
    timestamp = Column(DateTime(timezone=True), nullable=False, index=True,
                      comment="When the alert was triggered")
    created_at = Column(DateTime(timezone=True), server_default=func.now(),
                       nullable=False, comment="Database insertion timestamp")
    
    # Alert classification
    alert_type = Column(Enum(AlertType), nullable=False, index=True,
                       comment="Type of security alert")
    severity = Column(Enum(AlertSeverity), nullable=False, index=True,
                     comment="Alert severity level")
    
    # Alert details
    title = Column(String(200), nullable=False,
                  comment="Short alert title")
    description = Column(Text, nullable=False,
                        comment="Detailed alert description")
    
    # Source information
    src_ip = Column(String(45), nullable=True, index=True,
                   comment="Source IP address if applicable")
    dst_ip = Column(String(45), nullable=True,
                   comment="Destination IP address if applicable")
    dst_port = Column(Integer, nullable=True,
                     comment="Destination port if applicable")
    
    # Related data
    related_event_ids = Column(JSON, nullable=True,
                              comment="IDs of related network events")
    alert_metadata = Column(JSON, nullable=True,
                           comment="Additional alert metadata")
    
    # Alert management
    acknowledged = Column(Boolean, default=False, index=True,
                         comment="Whether the alert has been acknowledged")
    acknowledged_at = Column(DateTime(timezone=True), nullable=True,
                            comment="When the alert was acknowledged")
    acknowledged_by = Column(String(100), nullable=True,
                            comment="Who acknowledged the alert")
    
    # Resolution
    resolved = Column(Boolean, default=False, index=True,
                     comment="Whether the alert has been resolved")
    resolved_at = Column(DateTime(timezone=True), nullable=True,
                        comment="When the alert was resolved")
    resolution_notes = Column(Text, nullable=True,
                             comment="Notes about alert resolution")
    
    def __repr__(self) -> str:
        return (f"<SecurityAlert(id={self.id}, "
                f"type={self.alert_type.value}, "
                f"severity={self.severity.value}, "
                f"src_ip={self.src_ip}, "
                f"acknowledged={self.acknowledged})>")
    
    def to_dict(self) -> dict:
        """Convert model to dictionary for JSON serialization"""
        return {
            "id": self.id,
            "timestamp": self.timestamp.isoformat() if self.timestamp else None,
            "created_at": self.created_at.isoformat() if self.created_at else None,
            "alert_type": self.alert_type.value if self.alert_type else None,
            "severity": self.severity.value if self.severity else None,
            "title": self.title,
            "description": self.description,
            "src_ip": self.src_ip,
            "dst_ip": self.dst_ip,
            "dst_port": self.dst_port,
            "related_event_ids": self.related_event_ids,
            "metadata": self.alert_metadata,
            "acknowledged": self.acknowledged,
            "acknowledged_at": self.acknowledged_at.isoformat() if self.acknowledged_at else None,
            "acknowledged_by": self.acknowledged_by,
            "resolved": self.resolved,
            "resolved_at": self.resolved_at.isoformat() if self.resolved_at else None,
            "resolution_notes": self.resolution_notes
        }
    
    @classmethod
    def create_port_scan_alert(cls, src_ip: str, event_count: int, 
                              event_ids: list) -> "SecurityAlert":
        """
        Create a port scan alert
        
        Args:
            src_ip: Source IP address performing the scan
            event_count: Number of events detected
            event_ids: List of related event IDs
            
        Returns:
            SecurityAlert: New port scan alert
        """
        severity = AlertSeverity.HIGH if event_count > 20 else AlertSeverity.MEDIUM
        
        return cls(
            timestamp=datetime.utcnow(),
            alert_type=AlertType.PORT_SCAN,
            severity=severity,
            title=f"Port Scan Detected from {src_ip}",
            description=f"Detected {event_count} connection attempts from {src_ip} "
                       f"to multiple ports, indicating potential port scanning activity.",
            src_ip=src_ip,
            related_event_ids=event_ids,
            metadata={
                "event_count": event_count,
                "detection_method": "frequency_analysis"
            }
        )
    
    @classmethod
    def create_suspicious_port_alert(cls, src_ip: str, dst_ip: str, 
                                    dst_port: int, event_ids: list) -> "SecurityAlert":
        """
        Create a suspicious port access alert
        
        Args:
            src_ip: Source IP address
            dst_ip: Destination IP address
            dst_port: Suspicious destination port
            event_ids: List of related event IDs
            
        Returns:
            SecurityAlert: New suspicious port alert
        """
        return cls(
            timestamp=datetime.utcnow(),
            alert_type=AlertType.SUSPICIOUS_PORT,
            severity=AlertSeverity.MEDIUM,
            title=f"Suspicious Port Access: {dst_port}",
            description=f"Connection attempt from {src_ip} to {dst_ip}:{dst_port}. "
                       f"Port {dst_port} is commonly targeted by attackers.",
            src_ip=src_ip,
            dst_ip=dst_ip,
            dst_port=dst_port,
            related_event_ids=event_ids,
            metadata={
                "port": dst_port,
                "detection_method": "suspicious_port_list"
            }
        )